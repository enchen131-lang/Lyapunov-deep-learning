function output = Jtool(toolAng, flexLen, cameraLen)

phi = toolAng(1);
theta = toolAng(2);
len = flexLen;
L = cameraLen;

% J46
if theta == 0
    output = [0, cos(phi)*(0.5*len + L);...
        0, sin(phi)*(0.5*len + L);...
        0, 0;...
        0, -sin(phi);...
        0, cos(phi);...
        0, 0];
else 
    output = [(len*sin(phi)*(cos(theta) - 1))/theta - L*sin(phi)*sin(theta), (cos(phi)*(len*cos(theta) - len + len*theta*sin(theta) + L*theta^2*cos(theta)))/theta^2;...
        L*cos(phi)*sin(theta) - (len*cos(phi)*(cos(theta) - 1))/theta, (sin(phi)*(len*cos(theta) - len + len*theta*sin(theta) + L*theta^2*cos(theta)))/theta^2;...
        0, (len*cos(theta))/theta - L*sin(theta) - (len*sin(theta))/theta^2;...
        -cos(phi)*sin(theta), -sin(phi);...
        -sin(phi)*sin(theta), cos(phi);...
        1 - cos(theta), 0];
end

end